#!/usr/bin/env bash
#
# build.sh — compile with SwiftPM, assemble a macOS .app bundle, codesign.
#
# Usage:  ./build.sh [debug|release]
#
# Driven by the Makefile. NO Xcode IDE, NO xcodebuild — `swift build` does
# the compile, this script does the bundling and signing. Xcode is only a
# toolchain provider (swift / codesign).
#
# Environment:
#   SIGN_IDENTITY      codesign identity. Defaults to ad-hoc ("-"), which is
#                      all you need for `make run` on your own machine.
#   VERSION            CFBundleShortVersionString to stamp (default 0.0.0).
#
set -euo pipefail

CONFIG="${1:-debug}"
APP_NAME="TunedTwo"
CLI_NAME="tunedtwo-cli"
BUILD_DIR="build"
APP="$BUILD_DIR/$APP_NAME.app"
SIGN_IDENTITY="${SIGN_IDENTITY:--}"
VERSION="${VERSION:-0.0.0}"
ENTITLEMENTS="$APP_NAME/$APP_NAME.entitlements"
INFO_PLIST_SRC="Resources/Info.plist"
NRSC5_DYLIB_SRC="Vendor/nrsc5/build/src/libnrsc5.dylib"

# Build number: monotonic-ish from the date so re-signs differ. Falls back to 1.
BUILD_NUMBER="$(date +%Y%m%d%H%M 2>/dev/null || echo 1)"

echo "→ swift build -c $CONFIG"
swift build -c "$CONFIG" --product TunedTwo --product tunedtwo-cli

BIN_PATH="$(swift build -c "$CONFIG" --show-bin-path)"
EXECUTABLE="$BIN_PATH/$APP_NAME"
CLI_EXECUTABLE="$BIN_PATH/$CLI_NAME"
if [ ! -x "$EXECUTABLE" ]; then
	echo "✗ executable not found at $EXECUTABLE" >&2
	exit 1
fi
if [ ! -x "$CLI_EXECUTABLE" ]; then
	echo "✗ CLI executable not found at $CLI_EXECUTABLE" >&2
	exit 1
fi

# SwiftPM records the deployment target (26.0) as the binary's linked SDK
# version. macOS uses that value for "linked-on-or-after" checks that decide
# whether AppKit/SwiftUI render modern controls or fall back to legacy Aqua.
# Cap the SDK stamp at 26.0 so the app is treated as linked against macOS 26,
# which still enables the modern controls while avoiding 27-only behavioral
# drift. minOS stays at the deployment target.
SDK_VERSION="26.0"
echo "→ restamping executable LC_BUILD_VERSION sdk=$SDK_VERSION"
xcrun vtool -set-build-version macos 26.0 "$SDK_VERSION" \
	-replace -output "$EXECUTABLE.vtool" "$EXECUTABLE"
mv "$EXECUTABLE.vtool" "$EXECUTABLE"
chmod +x "$EXECUTABLE"

# ---------------------------------------------------------------------------
# Ensure libnrsc5 is built and ready.
# ---------------------------------------------------------------------------
if [ ! -f "$NRSC5_DYLIB_SRC" ]; then
	echo "→ libnrsc5 not found; building it now"
	scripts/build-nrsc5.sh
fi

# ---------------------------------------------------------------------------
# Assemble the app bundle
# ---------------------------------------------------------------------------
echo "→ assembling $APP"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources" "$APP/Contents/Frameworks"

cp "$EXECUTABLE" "$APP/Contents/MacOS/$APP_NAME"

# Info.plist — substitute version placeholders.
sed -e "s/__SHORT_VERSION__/$VERSION/g" \
    -e "s/__BUILD_VERSION__/$BUILD_NUMBER/g" \
    "$INFO_PLIST_SRC" > "$APP/Contents/Info.plist"

# PkgInfo — classic 8-byte file some macOS code paths still look for.
printf 'APPL????' > "$APP/Contents/PkgInfo"

# SwiftPM resource bundles — if any dependency ships a `*.bundle`, copy it
# into Contents/Resources so the app finds it once moved away from `.build`.
for bundle in "$BIN_PATH"/*.bundle; do
	if [ -e "$bundle" ]; then
		cp -R "$bundle" "$APP/Contents/Resources/"
		echo "  bundled $(basename "$bundle")"
	fi
done

# App icon (optional — generated by `make icon`).
if [ -f "$BUILD_DIR/AppIcon.icns" ]; then
	cp "$BUILD_DIR/AppIcon.icns" "$APP/Contents/Resources/AppIcon.icns"
else
	echo "  (no $BUILD_DIR/AppIcon.icns — run 'make icon'; bundling without one)"
fi

# Bundled sample I/Q file.
if [ -f "Resources/sample.bin" ]; then
	cp "Resources/sample.bin" "$APP/Contents/Resources/sample.bin"
else
	echo "✗ Resources/sample.bin missing" >&2
	exit 1
fi

# libnrsc5 dynamic library.
cp "$NRSC5_DYLIB_SRC" "$APP/Contents/Frameworks/libnrsc5.dylib"

# ---------------------------------------------------------------------------
# Assemble the CLI tool
# ---------------------------------------------------------------------------
echo "→ assembling $BUILD_DIR/$CLI_NAME"
rm -f "$BUILD_DIR/$CLI_NAME"
mkdir -p "$BUILD_DIR"
cp "$CLI_EXECUTABLE" "$BUILD_DIR/$CLI_NAME"
cp "$NRSC5_DYLIB_SRC" "$BUILD_DIR/libnrsc5.dylib"

# ---------------------------------------------------------------------------
# Codesign — try the named identity, fall back to ad-hoc so `make run`
# always works on a fresh machine without certs.
# ---------------------------------------------------------------------------
sign_args=(--force --sign "$SIGN_IDENTITY")
if [ -f "$ENTITLEMENTS" ]; then
	sign_args+=(--entitlements "$ENTITLEMENTS")
fi

echo "→ codesign app ($SIGN_IDENTITY)"
if ! codesign "${sign_args[@]}" "$APP" 2>/dev/null; then
	echo "  identity '$SIGN_IDENTITY' unavailable — falling back to ad-hoc (-)"
	codesign --force --sign - ${ENTITLEMENTS:+--entitlements "$ENTITLEMENTS"} "$APP"
fi

echo "→ codesign CLI ($SIGN_IDENTITY)"
if ! codesign --force --sign "$SIGN_IDENTITY" "$BUILD_DIR/$CLI_NAME" 2>/dev/null; then
	echo "  identity '$SIGN_IDENTITY' unavailable — falling back to ad-hoc (-)"
	codesign --force --sign - "$BUILD_DIR/$CLI_NAME"
fi

codesign --verify --verbose=1 "$APP"

echo "✓ built $APP and $BUILD_DIR/$CLI_NAME"
